const DYNAMIC_TRANSLATIONS = Object.entries(PT_BR_DYNAMIC_FRAGMENTS).sort(([left], [right]) => right.length - left.length);

export function ptBR(value: string): string {
  const exact = PT_BR_UI[value];
  if (exact !== undefined) return exact;
  const trimmed = value.trim();
  const trimmedExact = PT_BR_UI[trimmed];
  if (trimmedExact !== undefined) return `${value.slice(0, value.indexOf(trimmed))}${trimmedExact}${value.slice(value.indexOf(trimmed) + trimmed.length)}`;
  let translated = value;
  for (const [source, replacement] of DYNAMIC_TRANSLATIONS) translated = translated.replaceAll(source, replacement);
  return translated;
}

function localize(node: ReactNode): ReactNode {
  if (typeof node === "string") return ptBR(node);
  if (Array.isArray(node)) return node.map(localize);
  return node;
}

export function Text(props: ComponentProps<typeof NativeText>) {
  return createElement(NativeText, props, localize(props.children));
}
